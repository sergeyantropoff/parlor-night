"""Ничьи в русских шашках.

Регламент тренажёра — практическое толкование правил вида спорта «шашки»
для русской версии на 64-клеточной доске:

* ход — действие одной стороны;
* в записи партии нумерованный ход состоит из хода белых и ответа чёрных;
* ничья по отсутствию развития фиксируется после 15 таких нумерованных ходов,
  то есть после 30 полуходов подряд без взятия и без хода простой шашки;
* троекратное повторение — та же расстановка и та же очередь хода.

Короткое чтение «15 полуходов» обрывает обычный эндшпиль дамок, поэтому
тренажёр его не использует. Число закреплено константой NONPROGRESS_PLIES.

Отдельно действует технический предел партии. Он не входит в спортивные
правила и нужен, чтобы партия не росла без конца.
"""

from __future__ import annotations

NONPROGRESS_PLIES = 30
TECHNICAL_PLY_LIMIT = 400

REGULATION = (
    "Русские шашки, 64 клетки. Ничья: троекратное повторение позиции при той же "
    "очереди хода; 15 нумерованных ходов записи (30 полуходов) подряд без взятия "
    "и без перемещения простой шашки. Технический предел тренажёра — 400 полуходов."
)


def nonprogress_draw(clock: int) -> bool:
    return clock >= NONPROGRESS_PLIES


def repetition_draw(history: list[str]) -> bool:
    if not history:
        return False
    return history.count(history[-1]) >= 3


def technical_draw(ply: int) -> bool:
    return ply >= TECHNICAL_PLY_LIMIT
